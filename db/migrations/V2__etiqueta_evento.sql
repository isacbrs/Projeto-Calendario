-- Criação da tabela ETIQUETA
CREATE TABLE ETIQUETA (
    id_etiqueta INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_grupo INTEGER NOT NULL,
    nome VARCHAR(100) NOT NULL,
    cor VARCHAR(7) NOT NULL,
    data_hora_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_etiqueta PRIMARY KEY (id_etiqueta),
    CONSTRAINT ak_etiqueta_id_grupo UNIQUE (id_etiqueta, id_grupo),
    CONSTRAINT fk_etiqueta_grupo FOREIGN KEY (id_grupo) 
        REFERENCES GRUPO (id_grupo) ON DELETE CASCADE,
    CONSTRAINT ck_etiqueta_cor CHECK (cor ~ '^#[0-9A-Fa-f]{6}$')
);

-- Índice funcional para RINT03 (Unicidade de nome case-insensitive no mesmo grupo)
CREATE UNIQUE INDEX ak_etiqueta_grupo_nome ON ETIQUETA (id_grupo, LOWER(nome));

-- Criação da tabela EVENTO
CREATE TABLE EVENTO (
    id_evento INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_grupo INTEGER NOT NULL,
    id_criador INTEGER,
    id_etiqueta INTEGER,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    data_evento DATE NOT NULL,
    hora_inicio TIME,
    hora_termino TIME,
    antecedencia_dias INTEGER NOT NULL,
    data_hora_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_evento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_grupo FOREIGN KEY (id_grupo) 
        REFERENCES GRUPO (id_grupo) ON DELETE CASCADE,
    CONSTRAINT fk_evento_criador FOREIGN KEY (id_criador) 
        REFERENCES USUARIO (id_usuario) ON DELETE SET NULL,
    CONSTRAINT fk_evento_etiqueta FOREIGN KEY (id_etiqueta, id_grupo) 
        REFERENCES ETIQUETA (id_etiqueta, id_grupo) ON DELETE SET NULL (id_etiqueta),
    CONSTRAINT ck_evento_antecedencia CHECK (antecedencia_dias BETWEEN 1 AND 4),
    CONSTRAINT ck_evento_horarios CHECK (
        hora_termino IS NULL OR 
        (hora_inicio IS NOT NULL AND hora_termino > hora_inicio)
    )
);

-- Índices de chaves estrangeiras e buscas frequentes para EVENTO
CREATE INDEX idx_evento_criador ON EVENTO (id_criador);
CREATE INDEX idx_evento_etiqueta ON EVENTO (id_etiqueta);
CREATE INDEX idx_evento_grupo_data ON EVENTO (id_grupo, data_evento);

-- Criação da tabela NOTIFICACAO
CREATE TABLE NOTIFICACAO (
    id_notificacao INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_evento INTEGER NOT NULL,
    id_participacao INTEGER NOT NULL,
    data_hora_prevista TIMESTAMP WITH TIME ZONE NOT NULL,
    data_hora_efetiva TIMESTAMP WITH TIME ZONE,
    estado VARCHAR(15) NOT NULL,
    CONSTRAINT pk_notificacao PRIMARY KEY (id_notificacao),
    CONSTRAINT fk_notificacao_evento FOREIGN KEY (id_evento) 
        REFERENCES EVENTO (id_evento) ON DELETE CASCADE,
    CONSTRAINT fk_notificacao_participacao FOREIGN KEY (id_participacao) 
        REFERENCES PARTICIPACAO (id_participacao) ON DELETE CASCADE,
    CONSTRAINT ck_notificacao_estado CHECK (estado IN ('PENDENTE', 'ENVIADA', 'FALHA', 'CANCELADA'))
);

-- Índices de chaves estrangeiras para ações em cascata de NOTIFICACAO
CREATE INDEX idx_notificacao_evento ON NOTIFICACAO (id_evento);
CREATE INDEX idx_notificacao_participacao ON NOTIFICACAO (id_participacao);

-- Índice parcial para RINT08 (Máximo de uma notificação PENDENTE por par)
CREATE UNIQUE INDEX idx_notificacao_unica_pendente 
ON NOTIFICACAO (id_evento, id_participacao) 
WHERE estado = 'PENDENTE';

-- Índice parcial para otimizar as buscas do scheduler por data_hora_prevista
CREATE INDEX idx_notificacao_scheduler 
ON NOTIFICACAO (data_hora_prevista) 
WHERE estado = 'PENDENTE';